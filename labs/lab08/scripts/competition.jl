using DifferentialEquations, Plots, DelimitedFiles

# Параметры (вариант 9)
p_cr = 21      # критическая стоимость (тыс. ед.)
N = 24         # число потребителей (тыс. чел.)
q = 1.0        # макс. потребность одного человека

τ1 = 17        # длительность цикла фирмы 1
τ2 = 20        # длительность цикла фирмы 2
p1 = 14        # себестоимость фирмы 1 (тыс. ед.)
p2 = 12        # себестоимость фирмы 2 (тыс. ед.)

M1_0 = 2.6     # начальные оборотные средства фирмы 1 (млн. ед.)
M2_0 = 1.9     # начальные оборотные средства фирмы 2 (млн. ед.)

# Вычисляем коэффициенты
a1 = p_cr / (τ1^2 * p1^2 * N * q)
a2 = p_cr / (τ2^2 * p2^2 * N * q)
b = p_cr / (τ1^2 * τ2^2 * p1^2 * p2^2 * N * q)
c1 = (p_cr - p1) / (τ1 * p1)
c2 = (p_cr - p2) / (τ2 * p2)

# Отношения для системы
b_c1 = b / c1
a1_c1 = a1 / c1
a2_c1 = a2 / c1
c2_c1 = c2 / c1

println("\n" * "="^60)
println("МОДЕЛЬ КОНКУРЕНЦИИ ДВУХ ФИРМ (вариант 9)")
println("="^60)
println("Параметры:")
println("p_cr = $p_cr, N = $N, q = $q")
println("τ1 = $τ1, τ2 = $τ2")
println("p̃1 = $p1, p̃2 = $p2")
println("M1_0 = $M1_0, M2_0 = $M2_0")
println("\nКоэффициенты:")
println("a1 = $a1")
println("a2 = $a2")
println("b = $b")
println("c1 = $c1")
println("c2 = $c2")
println("\nОтношения:")
println("b/c1 = $b_c1")
println("a1/c1 = $a1_c1")
println("a2/c1 = $a2_c1")
println("c2/c1 = $c2_c1")
println("="^60)

# Безразмерное время
θ_span = (0.0, 30.0)
u0 = [M1_0, M2_0]

# ============================================================
# СЛУЧАЙ 1: только рыночные методы
# ============================================================
function case1!(du, u, p, θ)
    M1, M2 = u
    du[1] = M1 - b_c1 * M1 * M2 - a1_c1 * M1^2
    du[2] = c2_c1 * M2 - b_c1 * M1 * M2 - a2_c1 * M2^2
end

prob1 = ODEProblem(case1!, u0, θ_span)
sol1 = solve(prob1, Tsit5(), saveat=0.1)

# ============================================================
# СЛУЧАЙ 2: с социально-психологическим фактором
# ============================================================
function case2!(du, u, p, θ)
    M1, M2 = u
    du[1] = M1 - (b_c1 + 0.0018) * M1 * M2 - a1_c1 * M1^2
    du[2] = c2_c1 * M2 - b_c1 * M1 * M2 - a2_c1 * M2^2
end

prob2 = ODEProblem(case2!, u0, θ_span)
sol2 = solve(prob2, Tsit5(), saveat=0.1)

# ============================================================
# Построение графиков
# ============================================================

# График для случая 1
p1 = plot(sol1, 
          title="Случай 1 (только рыночные методы)",
          xlabel="Безразмерное время θ",
          ylabel="Оборотные средства M",
          label=["Фирма 1" "Фирма 2"],
          linewidth=2,
          legend=:topright)

# График для случая 2
p2 = plot(sol2,
          title="Случай 2 (с социально-психологическим фактором)",
          xlabel="Безразмерное время θ",
          ylabel="Оборотные средства M",
          label=["Фирма 1" "Фирма 2"],
          linewidth=2,
          legend=:topright)

# Объединяем графики
plot(p1, p2, layout=(2,1), size=(800, 1000))
savefig("competition_results.png")
display(plot(p1, p2, layout=(2,1), size=(800, 1000)))

println("\n✅ График сохранён в competition_results.png")

# ============================================================
# Стационарное состояние для случая 1
# ============================================================
# Приравниваем производные к нулю:
# M1 - b_c1*M1*M2 - a1_c1*M1^2 = 0
# c2_c1*M2 - b_c1*M1*M2 - a2_c1*M2^2 = 0

# Делим первое на M1 (M1 ≠ 0), второе на M2 (M2 ≠ 0):
# 1 - b_c1*M2 - a1_c1*M1 = 0  =>  a1_c1*M1 + b_c1*M2 = 1
# c2_c1 - b_c1*M1 - a2_c1*M2 = 0  =>  b_c1*M1 + a2_c1*M2 = c2_c1

# Решаем систему линейных уравнений:
# | a1_c1    b_c1  | | M1 | = | 1   |
# | b_c1     a2_c1 | | M2 |   | c2_c1|

det = a1_c1 * a2_c1 - b_c1^2
M1_ss = (1 * a2_c1 - b_c1 * c2_c1) / det
M2_ss = (a1_c1 * c2_c1 - b_c1 * 1) / det

println("\n" * "="^60)
println("СТАЦИОНАРНОЕ СОСТОЯНИЕ (случай 1)")
println("="^60)
println("M1* = $M1_ss")
println("M2* = $M2_ss")
println("="^60)

# ============================================================
# Анализ результатов
# ============================================================
M1_end1 = sol1[end][1]
M2_end1 = sol1[end][2]
M1_end2 = sol2[end][1]
M2_end2 = sol2[end][2]

println("\n" * "="^60)
println("РЕЗУЛЬТАТЫ МОДЕЛИРОВАНИЯ")
println("="^60)
println("Случай 1 (конечные значения):")
println("  M1 = $M1_end1")
println("  M2 = $M2_end1")
println("\nСлучай 2 (конечные значения):")
println("  M1 = $M1_end2")
println("  M2 = $M2_end2")

if M1_end1 > 0 && M2_end1 > 0
    println("\n👉 В случае 1 обе фирмы остаются на рынке")
elseif M1_end1 <= 0
    println("\n👉 В случае 1 фирма 1 обанкротилась")
elseif M2_end1 <= 0
    println("\n👉 В случае 1 фирма 2 обанкротилась")
end

if M1_end2 > 0 && M2_end2 > 0
    println("👉 В случае 2 обе фирмы остаются на рынке")
elseif M1_end2 <= 0
    println("👉 В случае 2 фирма 1 обанкротилась")
elseif M2_end2 <= 0
    println("👉 В случае 2 фирма 2 обанкротилась")
end

println("="^60)

# ============================================================
# Сохраняем результаты для отчёта
# ============================================================
mkpath("../report")

results = [
    "Параметр p_cr" p_cr
    "Параметр N" N
    "Параметр q" q
    "τ1" τ1
    "τ2" τ2
    "p̃1" p1
    "p̃2" p2
    "M1_0" M1_0
    "M2_0" M2_0
    "a1" a1
    "a2" a2
    "b" b
    "c1" c1
    "c2" c2
    "b/c1" b_c1
    "a1/c1" a1_c1
    "a2/c1" a2_c1
    "c2/c1" c2_c1
    "M1* (стац.)" M1_ss
    "M2* (стац.)" M2_ss
    "Случай 1: M1 кон." M1_end1
    "Случай 1: M2 кон." M2_end1
    "Случай 2: M1 кон." M1_end2
    "Случай 2: M2 кон." M2_end2
]

writedlm("../report/results.csv", results, ',')

cp("competition_results.png", "../report/competition_results.png", force=true)

println("\n✅ Результаты сохранены в report/")
